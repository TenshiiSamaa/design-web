const fs = require('fs');
const path = require('path');

const registryDir = path.join(__dirname, '..', 'features', 'components', 'registry');
const manifestPath = path.join(__dirname, '..', 'features', 'components', 'registry-manifest.ts');

console.log('Building Component Registry Manifest...');

const imports = [];
const exportsList = [];

// Recursively traverse directory to find all .tsx files
function traverse(dir) {
  const list = fs.readdirSync(dir);
  list.forEach(file => {
    const filePath = path.join(dir, file);
    const stat = fs.statSync(filePath);
    
    if (stat.isDirectory()) {
      traverse(filePath);
    } else if (file.endsWith('.tsx')) {
      const relativePath = './' + path.relative(path.join(__dirname, '..', 'features', 'components'), filePath)
        .replace(/\\/g, '/')
        .replace(/\.tsx$/, '');
      
      const componentName = file.replace('.tsx', '');
      const varName = `${componentName}Showcase`;
      
      imports.push(`import { ${componentName}Showcase as ${varName} } from "${relativePath}";`);
      exportsList.push(varName);
    }
  });
}

if (fs.existsSync(registryDir)) {
  traverse(registryDir);
}

const content = `// THIS FILE IS AUTOMATICALLY GENERATED. DO NOT EDIT DIRECTLY.
// Run "node scripts/build-component-registry.js" to regenerate.

${imports.join('\n')}

import { ComponentShowcase } from "./types";

export const ALL_COMPONENTS: ComponentShowcase[] = [
  ${exportsList.join(',\n  ')}
];
`;

fs.writeFileSync(manifestPath, content);
console.log(`Successfully generated component registry manifest with ${exportsList.length} showcases!`);
