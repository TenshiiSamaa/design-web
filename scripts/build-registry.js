/* eslint-disable @typescript-eslint/no-require-imports */
const fs = require('fs');
const path = require('path');

const CATEGORIES = [
  "professional", "minimal", "corporate", "purple", "blue", 
  "green", "warm", "neutral", "monochrome", "creative"
];

const registryDir = path.join(__dirname, '..', 'registry');
const manifestPath = path.join(registryDir, 'registry-manifest.ts');

console.log('Building Palette Registry Manifest...');

const imports = [];
const exportsList = [];

CATEGORIES.forEach(cat => {
  const catDir = path.join(registryDir, cat);
  if (!fs.existsSync(catDir)) return;

  const files = fs.readdirSync(catDir);
  files.forEach(file => {
    if (!file.endsWith('.ts')) return;
    const slug = file.replace('.ts', '');
    const varName = `${cat}_${slug.replace(/-/g, '_')}`;
    const relativePath = `./${cat}/${slug}`;
    
    imports.push(`import { ${slug.replace(/-/g, '_')} as ${varName} } from "${relativePath}";`);
    exportsList.push(varName);
  });
});

const content = `// THIS FILE IS AUTOMATICALLY GENERATED. DO NOT EDIT DIRECTLY.
// Run "node scripts/build-registry.js" to regenerate.

${imports.join('\n')}

import { Palette } from "./types";

export const ALL_PALETTES: Palette[] = [
  ${exportsList.join(',\n  ')}
];
`;

fs.writeFileSync(manifestPath, content);
console.log(`Successfully generated registry manifest with ${exportsList.length} palettes!`);
